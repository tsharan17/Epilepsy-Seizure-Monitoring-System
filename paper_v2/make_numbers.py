"""
Generate numbers.tex for the paper from the final evaluation outputs.

inputs in <results_dir>:
  summary.json            (run_eval/report: feature AUCs, signal stats)
  gain_sweep.json         (shipped detectors + LL-BR at gains 500/2000)
  manifest.json
  rigor_FP1-FP2.json      (rigor.py: LOSO/2-fold, nested, nulls, tests, ablations)
  rigor_FP1-F7.json, rigor_FP2-F8.json   (optional, secondary channels)
  hw_robustness.json      (optional, hw_robustness.py addendum)

usage: python make_numbers.py <results_dir> [--pilot "note"]
"""
import argparse
import json
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("results")
ap.add_argument("--pilot", default="")
a = ap.parse_args()
R = Path(a.results)
S = json.load(open(R / "summary.json"))
G = json.load(open(R / "gain_sweep.json"))
M = json.load(open(R / "manifest.json"))
RG = json.load(open(R / "rigor_FP1-FP2.json"))
SEC = {c: json.load(open(R / f"rigor_{c}.json")) for c in ("FP1-F7", "FP2-F8") if (R / f"rigor_{c}.json").exists()}
HW = json.load(open(R / "hw_robustness.json")) if (R / "hw_robustness.json").exists() else None
VAR = json.load(open(R / "variants_FP1-FP2.json")) if (R / "variants_FP1-FP2.json").exists() else None
FUS = json.load(open(R / "fusion_FP1-FP2.json")) if (R / "fusion_FP1-FP2.json").exists() else None

out = ["% AUTO-GENERATED by make_numbers.py — do not edit by hand", f"% source: {R}"]
mac = lambda k, v: out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
pc = lambda x: f"{100*x:.1f}\\%" if x == x else "--"
p0 = lambda x: f"{100*x:.0f}" if x == x else "--"
f2 = lambda x: f"{x:.2f}" if x == x else "--"
f1 = lambda x: f"{x:.1f}" if x == x else "--"
ci = lambda v: f"{p0(v[0])}--{p0(v[1])}\\%"

def ptxt(p):
    if p < 1e-3:
        m, e = f"{p:.0e}".split("e")
        return f"$p{{=}}{m}{{\\times}}10^{{{int(e)}}}$"
    return f"$p{{=}}{p:.3f}$" if p >= 0.001 else "$p{<}0.001$"

mac("Pilot", "1" if a.pilot else "0"); mac("PilotNote", a.pilot)
mac("NSubj", RG["subjects"]); mac("NRec", RG["recordings"]); mac("NSz", RG["seizures"])
mac("NHours", f"{RG['hours']:.0f}"); mac("NColdStart", RG["cold_start_seizures"])
# full selection (secondary channels)
if SEC:
    s7 = SEC["FP1-F7"]
    mac("NRecAll", s7["recordings"]); mac("NSzAll", s7["seizures"]); mac("NHoursAll", f"{s7['hours']:.0f}")

Mth = RG["methods"]
names = {"py_blackout": "PyB", "py_any": "PyA", "fw_blackout": "FwB",
         "loso_DEV_1.0": "DevA", "loso_DEV_0.5": "DevB", "loso_DEV_0.2": "DevC",
         "loso_LL_1.0": "LlA", "loso_LL_0.5": "LlB", "loso_FUSE_1.0": "FuA",
         "2fold_DEV_1.0": "TwoDevA", "2fold_DEV_0.5": "TwoDevB",
         "loso_NESTED_1.0": "NeA", "loso_NESTED_0.5": "NeB"}
for k, n in names.items():
    v = Mth[k]
    mac(f"{n}Sens", pc(v["sensitivity"])); mac(f"{n}Det", v["detected"]); mac(f"{n}CI", ci(v["sens_ci"]))
    mac(f"{n}Macro", pc(v["macro_sensitivity"])); mac(f"{n}MacroCI", ci(v["macro_ci"]))
    mac(f"{n}FAh", f2(v["fa_per_hour"])); mac(f"{n}FAday", f"{24*v['fa_per_hour']:.0f}")
    mac(f"{n}FACI", f"{f2(v['fah_ci'][0])}--{f2(v['fah_ci'][1])}")
    mac(f"{n}Lat", f1(v["latency_median"]))
for k, n in (("loso_DEV_1.0", "DevA"), ("loso_DEV_0.5", "DevB")):
    mac(f"{n}SensWarm", pc(Mth[k]["sensitivity_excl_coldstart"])); mac(f"{n}SzWarm", Mth[k]["seizures_excl_coldstart"])
from collections import Counter
for k, n in (("loso_DEV_1.0", "DevA"), ("loso_DEV_0.5", "DevB")):
    ch = RG["choices"][k]
    (rr, D), cnt = Counter((c["r"], c["D"]) for c in ch).most_common(1)[0]
    mac(f"{n}R", rr); mac(f"{n}D", D); mac(f"{n}ModeCount", cnt); mac(f"{n}Folds", len(ch))
nested_dev = sum(1 for k in ("loso_NESTED_1.0", "loso_NESTED_0.5", "loso_NESTED_0.2") for c in RG["choices"][k] if c["sig"] == "DEV")
nested_all = sum(len(RG["choices"][k]) for k in ("loso_NESTED_1.0", "loso_NESTED_0.5", "loso_NESTED_0.2"))
mac("NestedDev", nested_dev); mac("NestedAll", nested_all)

# empirical null
for k, n in (("py_blackout", "PyB"), ("py_any", "PyA"), ("fw_blackout", "FwB"), ("loso_DEV_1.0", "DevA"),
             ("loso_DEV_0.5", "DevB"), ("loso_LL_1.0", "LlA")):
    v = RG["nulls"][k]
    mac(f"{n}Null", pc(v["null_mean"])); mac(f"{n}NullNF", pc(v["null_p95"])); mac(f"{n}NullP", ptxt(v["p"]))
mac("NPerm", 1000)
mac("ShipNullMaxP", f"{max(RG['nulls'][k]['p'] for k in ('py_blackout','py_any','fw_blackout')):.3f}")
# subject tests
for k, n in (("loso_DEV_0.5_vs_py_blackout", "TestDevPy"), ("loso_DEV_1.0_vs_py_any", "TestDevPyAny"),
             ("loso_DEV_1.0_vs_LL_1.0", "TestDevLl")):
    t = RG["tests"][k]
    mac(f"{n}P", ptxt(t["p"])); mac(f"{n}Better", t["better"]); mac(f"{n}Worse", t["worse"]); mac(f"{n}Ties", t["ties"]); mac(f"{n}N", t["n"])
mac("FoldDevPy", f"{Mth['loso_DEV_0.5']['sensitivity']/max(Mth['py_blackout']['sensitivity'],1e-9):.0f}")

# feature AUCs (primary channel, from report.py)
fa = S["feature_auc"]
for k, n in (("Line-length", "LL"), ("Delta/alpha ratio", "DAR"), ("High-freq energy", "HFE"), ("Firmware abs(x−EMA)", "FW")):
    mac(f"Auc{n}", f"{fa[k]['pooled_auc']:.2f}"); mac(f"Auc{n}Case", f"{fa[k]['median_case_auc']:.2f}")
st = S["signal_stats"]["FP1-FP2"]
mac("ArtIctal", f"{100*st['ictal_artifact_frac']:.2f}\\%"); mac("ArtInter", f"{100*st['interictal_artifact_frac']:.2f}\\%")

# gain sweep of shipped analyzer
gl = {1000.0: Mth["py_blackout"]}
for k, v in G.items():
    gl[float(k)] = v["py"]
mac("PyBSensLowGain", pc(gl[500.0]["sensitivity"])); mac("PyBSensHighGain", pc(gl[2000.0]["sensitivity"]))
mac("PyBFAhLowGain", f2(gl[500.0]["fa_per_hour"])); mac("PyBFAhHighGain", f2(gl[2000.0]["fa_per_hour"]))
fwg = {1000.0: Mth["fw_blackout"]}; fwg.update({float(k): v["fw"] for k, v in G.items()})
mac("FwBFAhLowGain", f2(fwg[500.0]["fa_per_hour"])); mac("FwBFAhHighGain", f2(fwg[2000.0]["fa_per_hour"]))

# main table
def row(lab, v, bold=False, chance=None):
    L = f"\\textbf{{{lab}}}" if bold else lab
    return (f"{L} & {v['detected']}/{v['seizures']} & {pc(v['sensitivity'])} [{p0(v['sens_ci'][0])}--{p0(v['sens_ci'][1])}] & "
            f"{pc(v['macro_sensitivity'])} & {f2(v['fa_per_hour'])} & {f1(v['latency_median'])} & {chance} \\\\")
nul = RG["nulls"]
body = [row("Analyzer, BLACKOUT (shipped)", Mth["py_blackout"], chance=pc(nul["py_blackout"]["null_mean"])),
        row("Analyzer, any alarm (shipped)", Mth["py_any"], chance=pc(nul["py_any"]["null_mean"])),
        row("Firmware, BLACKOUT (shipped)", Mth["fw_blackout"], chance=pc(nul["fw_blackout"]["null_mean"])),
        "\\midrule",
        row("LL-BR, $\\le$1 FA/h", Mth["loso_LL_1.0"], chance=pc(nul["loso_LL_1.0"]["null_mean"])),
        row("FUSE-BR, $\\le$1 FA/h", Mth["loso_FUSE_1.0"], chance="--"),
        row("DEV-BR, $\\le$1 FA/h", Mth["loso_DEV_1.0"], True, chance=pc(nul["loso_DEV_1.0"]["null_mean"])),
        row("DEV-BR, $\\le$0.5 FA/h", Mth["loso_DEV_0.5"], True, chance=pc(nul["loso_DEV_0.5"]["null_mean"])),
        row("DEV-BR, $\\le$0.2 FA/h", Mth["loso_DEV_0.2"], True, chance="--")]
out.append("\\newcommand{\\MainTableBody}{%\n" + "\n".join(body) + "\n}")

# ablation table (LOSO, DEV)
A = RG["ablation"]
lab = {"lag0": "no lag (0 s)", "lag10": "lag 10 s", "lag60": "lag 60 s", "win60": "window 60 s",
       "win120": "window 120 s", "win600": "window 600 s", "mean": "mean instead of median",
       "absolute": "no normalization (absolute)"}
rows = [f"\\textbf{{reference}} (300 s, lag 30 s, median) & {pc(Mth['loso_DEV_1.0']['sensitivity'])} / {f2(Mth['loso_DEV_1.0']['fa_per_hour'])} & "
        f"{pc(Mth['loso_DEV_0.5']['sensitivity'])} / {f2(Mth['loso_DEV_0.5']['fa_per_hour'])} \\\\"]
for k in ("lag0", "lag10", "lag60", "win60", "win120", "win600", "mean", "absolute"):
    v = A[k]
    rows.append(f"{lab[k]} & {pc(v['1.0']['sensitivity'])} / {f2(v['1.0']['fa_per_hour'])} & "
                f"{pc(v['0.5']['sensitivity'])} / {f2(v['0.5']['fa_per_hour'])} \\\\")
alt = []
if VAR:
    vm = VAR["methods"]
    for k, l in (("KOFN", "k-of-n persistence"), ("DUAL", "dual time-scale rule"), ("CONT_BASE", "baseline carried across files")):
        alt.append(f"{l} & {pc(vm[k+'_1.0']['sensitivity'])} / {f2(vm[k+'_1.0']['fa_per_hour'])} & "
                   f"{pc(vm[k+'_0.5']['sensitivity'])} / {f2(vm[k+'_0.5']['fa_per_hour'])} \\\\")
if FUS:
    fm = FUS["methods"]
    for k, l in (("lr_fw", "log.\\ regression, firmware features"), ("lr_all", "log.\\ regression, all features"),
                 ("gbm_all", "boosted trees, all features")):
        if f"{k}_1.0" in fm and f"{k}_0.5" in fm:
            alt.append(f"{l} & {pc(fm[k+'_1.0']['sensitivity'])} / {f2(fm[k+'_1.0']['fa_per_hour'])} & "
                       f"{pc(fm[k+'_0.5']['sensitivity'])} / {f2(fm[k+'_0.5']['fa_per_hour'])} \\\\")
altv = []
if VAR:
    for k in ("KOFN", "DUAL", "CONT_BASE"):
        altv.append((VAR["methods"][k+"_1.0"]["sensitivity"], VAR["methods"][k+"_0.5"]["sensitivity"]))
if FUS:
    for k in ("lr_fw", "lr_all", "gbm_all"):
        if f"{k}_1.0" in FUS["methods"]:
            altv.append((FUS["methods"][k+"_1.0"]["sensitivity"], FUS["methods"][k+"_0.5"]["sensitivity"]))
if altv:
    mac("AltBestOneSens", pc(max(a for a, b in altv))); mac("AltBestHalfSens", pc(max(b for a, b in altv)))
if FUS and "gbm_all_0.5" in FUS["methods"]:
    mac("GbmOneSens", pc(FUS["methods"]["gbm_all_1.0"]["sensitivity"]))
    mac("GbmHalfSens", pc(FUS["methods"]["gbm_all_0.5"]["sensitivity"]))
    _t = FUS["tests"]["gbm_all_0.5_vs_DEV"]
    mac("GbmHalfBetter", str(_t["better"])); mac("GbmHalfWorse", str(_t["worse"])); mac("GbmHalfP", f"$p{{=}}{_t['p']:.2f}$")
if alt:
    rows.append("\\midrule")
    rows += alt
out.append("\\newcommand{\\AblationTableBody}{%\n" + "\n".join(rows) + "\n}")
mac("AblAbsSens", pc(A["absolute"]["1.0"]["sensitivity"])); mac("AblLagZeroSensB", pc(A["lag0"]["0.5"]["sensitivity"]))
mac("AblMeanSens", pc(A["mean"]["1.0"]["sensitivity"])); mac("AblWinLongSens", pc(A["win600"]["1.0"]["sensitivity"]))

# secondary channels (LOSO)
rows = []
for c, v in SEC.items():
    m = v["methods"]
    rows.append(f"{c} & {pc(m['py_any']['sensitivity'])} / {f2(m['py_any']['fa_per_hour'])} & "
                f"{pc(m['fw_blackout']['sensitivity'])} / {f2(m['fw_blackout']['fa_per_hour'])} & "
                f"{pc(m['loso_LL_1.0']['sensitivity'])} / {f2(m['loso_LL_1.0']['fa_per_hour'])} & "
                f"{pc(m['loso_DEV_1.0']['sensitivity'])} / {f2(m['loso_DEV_1.0']['fa_per_hour'])} \\\\")
    tag = "One" if c == "FP1-F7" else "Two"
    mac("DevSens" + tag, pc(m["loso_DEV_1.0"]["sensitivity"]))
    mac("SecLlP" + tag, ptxt(v["tests"]["loso_DEV_1.0_vs_LL_1.0"]["p"]))
    mac("SecNestedDev" + tag, sum(1 for k in ("loso_NESTED_1.0", "loso_NESTED_0.5", "loso_NESTED_0.2") for x in v["choices"][k] if x["sig"] == "DEV"))
out.append("\\newcommand{\\SecondaryTableBody}{%\n" + "\n".join(rows) + "\n}")

# hardware-robustness addendum
mac("HwAvailable", "1" if HW else "0")
if HW:
    rows = []
    labs = {"g500": "$\\times$500", "g1000": "$\\times$1000 (ref.)", "g2000": "$\\times$2000",
            "g1000_clip": "$\\times$1000, LM358 clip", "g2000_clip": "$\\times$2000, LM358 clip",
            "g1000_adc31": "$\\times$1000, 3.1-V ADC", "g1000_166Hz": "$\\times$1000, 167-Hz loop"}
    for k, l in labs.items():
        v = HW[k]
        rows.append(f"{l} & {100*v['sat']:.2f}\\% & {pc(v['fixed_1.0']['sensitivity'])} / {f2(v['fixed_1.0']['fa_per_hour'])} & "
                    f"{pc(v['loso_1.0']['sensitivity'])} / {f2(v['loso_1.0']['fa_per_hour'])} & "
                    f"{pc(v['firmware_blackout']['sensitivity'])} / {f2(v['firmware_blackout']['fa_per_hour'])} \\\\")
    out.append("\\newcommand{\\HwTableBody}{%\n" + "\n".join(rows) + "\n}")
    fr, fD = HW["fixed_params"]["1.0"]
    mac("HwFixR", fr); mac("HwFixD", fD)
    conds = [k for k in labs]
    fs = [HW[k]["fixed_1.0"]["sensitivity"] for k in conds]; ff = [HW[k]["fixed_1.0"]["fa_per_hour"] for k in conds]
    ws = [HW[k]["firmware_blackout"]["sensitivity"] for k in conds]; wf = [HW[k]["firmware_blackout"]["fa_per_hour"] for k in conds]
    mac("HwDevSensMin", pc(min(fs))); mac("HwDevSensMax", pc(max(fs)))
    mac("HwDevFAMin", f2(min(ff))); mac("HwDevFAMax", f2(max(ff)))
    mac("HwFwSensMin", pc(min(ws))); mac("HwFwSensMax", pc(max(ws)))
    mac("HwFwFAMin", f2(min(wf))); mac("HwFwFAMax", f2(max(wf)))
    gs = [HW[k]["fixed_1.0"]["sensitivity"] for k in ("g500", "g1000", "g2000")]
    mac("HwGainSens", pc(gs[0]) if len(set(round(x, 6) for x in gs)) == 1 else f"{pc(min(gs))}--{pc(max(gs))}")
    mac("HwClipSat", f"{100*HW['g2000_clip']['sat']:.1f}\\%"); mac("HwClipSens", pc(HW['g2000_clip']['fixed_1.0']['sensitivity']))
else:
    out.append("\\newcommand{\\HwTableBody}{}")

Path("numbers.tex").write_text("\n".join(out) + "\n")
print(f"wrote numbers.tex ({sum(1 for l in out if l.startswith(chr(92)+'newcommand'))} macros); HW={'yes' if HW else 'no'}; secondary={list(SEC)}")
