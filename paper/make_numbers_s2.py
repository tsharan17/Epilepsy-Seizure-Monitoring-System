"""numbers_s2.tex from SeizeIT2 results (s2_results.json, verify_cpp.json).
usage: python make_numbers_s2.py <s2out>"""
import json, sys
from collections import Counter
from pathlib import Path
R = Path(sys.argv[1]); D = json.load(open(R / "s2_results.json"))
V = json.load(open(R / "verify_cpp.json")) if (R / "verify_cpp.json").exists() else None
out = ["% AUTO-GENERATED by make_numbers_s2.py — do not edit by hand"]
mac = lambda k, v: out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
pc = lambda x: f"{100*x:.1f}\\%" if x == x else "--"
p0 = lambda x: f"{100*x:.0f}" if x == x else "--"
f2 = lambda x: f"{x:.2f}" if x == x else "--"
f1 = lambda x: f"{x:.1f}" if x == x else "--"
def ptxt(p):
    if p < 1e-3:
        m, e = f"{p:.0e}".split("e"); return f"$p{{=}}{m}{{\\times}}10^{{{int(e)}}}$"
    return f"$p{{=}}{p:.3f}$"
M = D["methods"]; cc = D["class_counts"]
mac("SNSubj", D["n_subjects"]); mac("SNRuns", D["n_runs"]); mac("SNSz", D["n_seizures"])
mac("SHours", f"{D['hours']:,.0f}".replace(",", "{,}")); mac("SMovMissing", D["n_mov_missing"])
mac("SNMotor", cc.get("focal motor", 0)); mac("SNNonMotor", cc.get("focal non-motor", 0))
mac("SNFBTC", cc.get("FBTC/generalized", 0)); mac("SNOther", cc.get("other/unknown", 0))
mac("SFwTarget", f2(D["fw_target"]))
CLS = [("focal motor", "Mot"), ("focal non-motor", "NonMot"), ("FBTC/generalized", "FBTC"), ("vig:asleep", "Sleep"), ("vig:awake", "Awake")]
mac("SNSleep", M["FW"]["by_class"].get("vig:asleep", {}).get("n", 0))
tags = {"FW": "Fw", "EEG_1.0": "EegA", "EEG_0.5": "EegB", "EEG_0.25": "EegC", "MOV_1.0": "MovA", "MOV_0.5": "MovB",
        "MOV_0.25": "MovC", "FUSED_1.0": "FusA", "FUSED_0.5": "FusB", "FUSED_0.25": "FusC", "COACT_1.0": "CoA",
        "COACT_0.5": "CoB", "MOVGYR_1.0": "GyrA", "MOVGYR_0.5": "GyrB", "EEG_atFW": "EegFw", "FUSED_atFW": "FusFw"}
for k, t in tags.items():
    m = M[k]
    mac(f"S{t}Sens", pc(m["sensitivity"])); mac(f"S{t}Det", m["detected"]); mac(f"S{t}FAh", f2(m["fa_per_hour"]))
    mac(f"S{t}FAday", f1(m["fa_per_day"])); mac(f"S{t}Macro", pc(m["macro_sensitivity"]))
    mac(f"S{t}CI", f"{p0(m['sens_ci'][0])}--{p0(m['sens_ci'][1])}\\%"); mac(f"S{t}Lat", f1(m["latency_median"]))
    for c, ct in CLS:
        v = m["by_class"].get(c); mac(f"S{t}{ct}", pc(v["sens"]) if v else "--")
    if "null" in m:
        mac(f"S{t}Null", pc(m["null"]["null_mean"])); mac(f"S{t}NullP", ptxt(m["null"]["p"]))
for k, v in D["tests"].items():
    t = k.replace("_vs_", "V").replace("_atFW", "Fw").replace("_1.0", "A").replace("_0.5", "B").replace("_", "")
    t = "".join(ch for ch in t if ch.isalpha())
    mac(f"ST{t}Better", v["better"]); mac(f"ST{t}Worse", v["worse"]); mac(f"ST{t}P", ptxt(v["p"]))
# modal parameters of the fused detector at <=1 FA/h
ch = Counter(c["key"] for c in D["choices"]["FUSED_1.0"]).most_common(1)[0]

if V:
    mac("SVerRuns", V["runs"]); mac("SVerSame", V["identical"]); mac("SVerAlarms", f"{V['alarms']:,}".replace(",", "{,}"))
    mac("SVerNote", f"({V['identical']} of {V['runs']} SeizeIT2 recordings identical, " + f"{V['alarms']:,}".replace(",", "{,}") + " alarms)")
else:
    mac("SVerNote", "(verification pending)")
T = json.load(open(R / "s2_tc_detail.json")) if (R / "s2_tc_detail.json").exists() else None
if T:
    for k, t in (("COACT_0.02", "CvA"), ("EEG_0.02", "CvEeg"), ("MOV_0.02", "CvMov"), ("COACT_0.05", "CvB")):
        v = T[k]
        mac(f"S{t}Det", v["det"]); mac(f"S{t}N", v["n"]); mac(f"S{t}Sens", pc(v["sens"]))
        mac(f"S{t}CI", f"{p0(v['ci'][0])}--{p0(v['ci'][1])}\\%"); mac(f"S{t}Subj", v["n_subj"])
        mac(f"S{t}FAday", f2(v["fa_per_day"])); mac(f"S{t}Lat", f"{v['lat_median']:.0f}")
        mac(f"S{t}LatIQR", f"{v['lat_iqr'][0]:.0f}--{v['lat_iqr'][1]:.0f}")
        mac(f"S{t}SleepDet", v["sleep_det"]); mac(f"S{t}SleepN", v["sleep_n"]); mac(f"S{t}ZeroFA", v["subj_zero_fa"])
    for b, t in (("EEG_0.02", "Eeg"), ("MOV_0.02", "Mov")):
        v = T[f"mcnemar_COACT_vs_{b}"]
        mac(f"SMc{t}Only", v["only_coact"]); mac(f"SMc{t}Other", v["only_other"]); mac(f"SMc{t}P", ptxt(v["p"]))
    CH = D["choices"]
    for k, t in (("TC_COACT_0.02", "CvAParams"), ("FUSED_1.0", "FusAParams")):
        c = Counter(x["key"] for x in CH[k]).most_common(1)[0]
        mac(f"S{t}N", c[1])
rows = []
CL4 = ["FBTC/generalized", "focal motor", "focal non-motor", "vig:asleep"]
def row(lbl, m):
    n = m.get("null")
    cells = [lbl, f"{m['detected']}/{m['seizures']}", f"{pc(m['sensitivity'])} [{p0(m['sens_ci'][0])}--{p0(m['sens_ci'][1])}]",
             f2(m["fa_per_hour"]) if m["fa_per_hour"] >= 0.1 else f"{m['fa_per_hour']:.3f}"]
    cells += [pc(m["by_class"][c]["sens"]) if c in m["by_class"] else "--" for c in CL4]
    cells += [pc(n["null_mean"]) if n else "--"]
    rows.append(" & ".join(cells) + " \\\\")
sec = lambda t: rows.append("\\multicolumn{9}{l}{\\textit{" + t + "}} \\\\")
row("Initial firmware (BLACKOUT)", M["FW"])
sec("Same false-alarm rate as the initial firmware")
row("EEG: DEV-BR", M["EEG_atFW"]); row("EEG or motion", M["FUSED_atFW"])
sec("General mode, $\\le$1 FA/h target")
row("EEG: DEV-BR", M["EEG_1.0"]); row("Motion: MOV-BR", M["MOV_1.0"]); row("EEG or motion", M["FUSED_1.0"])
out.append("\\newcommand{\\SMainTableBody}{%\n" + "\n".join(rows) + "\n}")
(Path(__file__).parent / "numbers_s2.tex").write_text("\n".join(out) + "\n")
print("wrote numbers_s2.tex", len(out))
