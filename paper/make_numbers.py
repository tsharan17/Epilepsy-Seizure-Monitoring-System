"""
Generate numbers.tex (macros + table bodies) for the paper.

inputs (one results folder = unzipped vera_results.zip + features/ + the
outputs of personalize.py and final_analysis.py):
  summary.json, gain_sweep.json, manifest.json, final.json, personal_FP1-FP2.json

usage: python make_numbers.py <results_dir> [--pilot "note"]
"""
import argparse
import json
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("results")
ap.add_argument("--pilot", default="")
a = ap.parse_args()
R = Path(a.results)
S = json.load(open(R / "summary.json"))
F = json.load(open(R / "final.json"))
PER = json.load(open(R / "personal_FP1-FP2.json"))
G = json.load(open(R / "gain_sweep.json"))
M = json.load(open(R / "manifest.json"))
P = "FP1-FP2"
f = F[P]["methods"]

out = ["% AUTO-GENERATED by make_numbers.py — do not edit by hand", f"% source: {R}"]
mac = lambda k, v: out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
pc = lambda x: f"{100*x:.1f}\\%" if x == x else "--"
p0 = lambda x: f"{100*x:.0f}" if x == x else "--"
f2 = lambda x: f"{x:.2f}" if x == x else "--"
f1 = lambda x: f"{x:.1f}" if x == x else "--"

mac("Pilot", "1" if a.pilot else "0"); mac("PilotNote", a.pilot)
mac("PrimaryCh", P)
mac("NPat", F[P]["n_patients"]); mac("NRec", F[P]["n_records"])
mac("NSz", F[P]["n_seizures"]); mac("NHours", f"{F[P]['hours']:.0f}")
mac("NSzAll", F["FP1-F7"]["n_seizures"]); mac("NHoursAll", f"{F['FP1-F7']['hours']:.0f}")

names = {"py_blackout": "PyB", "py_any": "PyA", "fw_blackout": "FwB", "fw_any": "FwA",
         "LL_1.0": "LlA", "LL_0.5": "LlB", "LL_0.2": "LlC",
         "DEV_1.0": "DevA", "DEV_0.5": "DevB", "DEV_0.2": "DevC",
         "FUSE_1.0": "FuA", "FUSE_0.5": "FuB", "FUSE_0.2": "FuC"}
for k, n in names.items():
    v = f[k]
    mac(f"{n}Sens", pc(v["sensitivity"])); mac(f"{n}Det", v["detected"])
    mac(f"{n}CI", f"{p0(v['sens_ci'][0])}--{p0(v['sens_ci'][1])}\\%")
    mac(f"{n}FAh", f2(v["fa_per_hour"])); mac(f"{n}FAday", f1(v["fa_per_24h"]))
    mac(f"{n}FACI", f"{f2(v['fah_ci'][0])}--{f2(v['fah_ci'][1])}")
    mac(f"{n}Lat", f1(v["latency_median"])); mac(f"{n}Chance", pc(v["chance"]))
for k, n in (("DEV_1.0", "DevA"), ("DEV_0.5", "DevB"), ("DEV_0.2", "DevC")):
    ch = f[k]["chosen"]
    mac(f"{n}Params", "; ".join(f"$r{{=}}{c[1]}$, $D{{=}}{c[2]}$\\,s" for c in ch))

T = F["tests"]
def ptxt(p):
    if p < 1e-3:
        m, e = f"{p:.0e}".split("e")
        return f"$p{{=}}{m}{{\\times}}10^{{{int(e)}}}$"
    return f"$p{{=}}{p:.3f}$"
for k, n in (("DEV_0.5_vs_py_blackout", "TestDevPy"), ("DEV_1.0_vs_py_any", "TestDevPyAny"),
             ("DEV_1.0_vs_LL_1.0", "TestDevLl")):
    t = T[k]
    mac(f"{n}P", ptxt(t["p"])); mac(f"{n}Better", t["better"]); mac(f"{n}Worse", t["worse"]); mac(f"{n}N", t["n"])
mac("FoldDevPy", f"{f['DEV_0.5']['sensitivity']/max(f['py_blackout']['sensitivity'],1e-9):.0f}")

fa = S["feature_auc"]
for k, n in (("Line-length", "LL"), ("Delta/alpha ratio", "DAR"), ("High-freq energy", "HFE"),
             ("Firmware abs(x−EMA)", "FW")):
    mac(f"Auc{n}", f"{fa[k]['pooled_auc']:.2f}"); mac(f"Auc{n}Case", f"{fa[k]['median_case_auc']:.2f}")
    mac(f"Med{n}Ictal", f"{fa[k]['ictal_median']:.3g}"); mac(f"Med{n}Inter", f"{fa[k]['interictal_median']:.3g}")
st = S["signal_stats"][P]
mac("ArtIctal", f"{100*st['ictal_artifact_frac']:.2f}\\%")
mac("ArtInter", f"{100*st['interictal_artifact_frac']:.2f}\\%")

# personalization
w = PER["wear"]; t = PER["tap"]
mac("WearPat", w["eval"]["patients"]); mac("WearSz", w["eval"]["seizures"]); mac("WearH", f"{w['eval']['hours']:.0f}")
mac("WearInH", f"{w['eval']['wear_hours']:.0f}")
for tgt, n in (("1.0", "A"), ("0.5", "B")):
    x = w[f"DEV_{tgt}"]
    mac(f"WearPop{n}Sens", pc(x["population"]["sensitivity"])); mac(f"WearPop{n}FAh", f2(x["population"]["fa_per_hour"]))
    mac(f"WearSelf{n}Sens", pc(x["self"]["sensitivity"])); mac(f"WearSelf{n}FAh", f2(x["self"]["fa_per_hour"]))
    y = t[f"DEV_{tgt}"]
    mac(f"TapPop{n}Sens", pc(y["population"]["sensitivity"])); mac(f"TapPop{n}FAh", f2(y["population"]["fa_per_hour"]))
    mac(f"TapSelf{n}Sens", pc(y["personal"]["sensitivity"])); mac(f"TapSelf{n}FAh", f2(y["personal"]["fa_per_hour"]))
mac("TapSz", t["eval"]["seizures"]); mac("TapH", f"{t['eval']['hours']:.0f}")

# gain sweep (shipped analyzer / firmware; LL-ratio CV as gain-invariant control)
gl = {float(M["gain"]): (f["py_blackout"], f["fw_blackout"], f["LL_0.5"])}
for k, v in G.items():
    gl[float(k)] = (v["py"], v["fw"], v["llr_cv"]["0.5"])
rows = []
for g in sorted(gl):
    py, fw, ll = gl[g]
    rows.append(f"$\\times${g:.0f} & {pc(py['sensitivity'])} / {f2(py['fa_per_hour'])} & "
                f"{pc(fw['sensitivity'])} / {f2(fw['fa_per_hour'])} & {pc(ll['sensitivity'])} / {f2(ll['fa_per_hour'])} \\\\")
out.append("\\newcommand{\\GainTableBody}{%\n" + "\n".join(rows) + "\n}")
g5, g20 = gl[500.0], gl[2000.0]
mac("PyBSensLowGain", pc(g5[0]["sensitivity"])); mac("PyBSensHighGain", pc(g20[0]["sensitivity"]))
mac("PyBFAhHighGain", f2(g20[0]["fa_per_hour"]))

# main table: primary channel, shipped + proposed
def row(lab, v, bold=False):
    L = f"\\textbf{{{lab}}}" if bold else lab
    return (f"{L} & {v['detected']}/{v['seizures']} & {pc(v['sensitivity'])} [{p0(v['sens_ci'][0])}--{p0(v['sens_ci'][1])}] & "
            f"{f2(v['fa_per_hour'])} & {f1(v['latency_median'])} & {pc(v['chance'])} \\\\")
body = [row("Analyzer, BLACKOUT (shipped)", f["py_blackout"]), row("Analyzer, any alarm (shipped)", f["py_any"]),
        row("Firmware, BLACKOUT (shipped)", f["fw_blackout"]), "\\midrule",
        row("LL-BR, $\\le$1 FA/h", f["LL_1.0"]), row("FUSE-BR, $\\le$1 FA/h", f["FUSE_1.0"]),
        row("DEV-BR, $\\le$1 FA/h", f["DEV_1.0"], True), row("DEV-BR, $\\le$0.5 FA/h", f["DEV_0.5"], True),
        row("DEV-BR, $\\le$0.2 FA/h", f["DEV_0.2"], True)]
out.append("\\newcommand{\\MainTableBody}{%\n" + "\n".join(body) + "\n}")

# secondary channels: compact
rows = []
for ch in ("FP1-F7", "FP2-F8"):
    m = F[ch]["methods"]
    rows.append(f"{ch} & {pc(m['py_any']['sensitivity'])} / {f2(m['py_any']['fa_per_hour'])} & "
                f"{pc(m['fw_blackout']['sensitivity'])} / {f2(m['fw_blackout']['fa_per_hour'])} & "
                f"{pc(m['LL_1.0']['sensitivity'])} / {f2(m['LL_1.0']['fa_per_hour'])} & "
                f"{pc(m['DEV_1.0']['sensitivity'])} / {f2(m['DEV_1.0']['fa_per_hour'])} \\\\")
out.append("\\newcommand{\\SecondaryTableBody}{%\n" + "\n".join(rows) + "\n}")
for ch, n in (("FP1-F7", "One"), ("FP2-F8", "Two")):
    mac(f"Dev{n}Sens", pc(F[ch]["methods"]["DEV_1.0"]["sensitivity"]))

Path("numbers.tex").write_text("\n".join(out) + "\n")
print(f"wrote numbers.tex ({sum(1 for l in out if l.startswith(chr(92)+'newcommand'))} macros)")
