"""numbers_audit.tex: audit re-analysis (convulsive mode restricted to recordings with a motion channel,
class-specific chance, patient-level paired tests) + FP1-FP2 reconstruction checks.
usage: python make_numbers_audit.py   (reads ../evaluation/results/audit/*.json)"""
import json
from pathlib import Path
H = Path(__file__).parent; A = json.load(open(H.parent / "evaluation" / "results" / "audit" / "audit_s2.json")); RT = json.load(open(H.parent / "evaluation" / "results" / "audit" / "recon_test.json"))
DT = json.load(open(H.parent / "evaluation" / "results" / "audit" / "audit_s2_detail.json")) if (H.parent / "evaluation" / "results" / "audit" / "audit_s2_detail.json").exists() else None
out = ["% AUTO-GENERATED by make_numbers_audit.py"]; mac = lambda k, v: out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
pc = lambda x: f"{100*x:.1f}\\%"; p0 = lambda x: f"{100*x:.0f}"
def ptxt(p):
    if p < 1e-3:
        m, e = f"{p:.0e}".split("e"); return f"$p{{=}}{m}{{\\times}}10^{{{int(e)}}}$"
    return f"$p{{=}}{p:.3f}$"
I = A["info"]
mac("AvRuns", I["runs_mov"]); mac("AvAllRuns", I["runs_all"]); mac("AvHours", f"{I['hours_mov']:,.0f}".replace(",", "{,}"))
mac("AvFbtc", I["f2b_mov"]); mac("AvFbtcAll", I["f2b_all"]); mac("AvSubj", A["paired_COACT_vs_EEG_0.02"]["subjects"])
for key, t in (("COACT_0.02", "CoA"), ("EEG_0.02", "EgA"), ("MOV_0.02", "MvA"), ("COACT_0.05", "CoB"), ("EEG_0.05", "EgB"), ("MOV_0.05", "MvB")):
    m = A["modes"][key]
    mac(f"Av{t}Det", m["det"]); mac(f"Av{t}N", m["n"]); mac(f"Av{t}Sens", pc(m["sens"])); mac(f"Av{t}CI", f"{p0(m['ci'][0])}--{p0(m['ci'][1])}\\%")
    mac(f"Av{t}FAday", f"{m['fa_per_day']:.2f}"); mac(f"Av{t}Null", pc(m["null_mean"])); mac(f"Av{t}NullP", pc(m["null_p95"])); mac(f"Av{t}PNull", ptxt(m["p_null"]))
for o, t in (("EEG", "Eeg"), ("MOV", "Mov")):
    for tg, u in ((0.02, "A"), (0.05, "B")):
        v = A[f"paired_COACT_vs_{o}_{tg}"]
        mac(f"Av{t}{u}Better", v["subj_better"]); mac(f"Av{t}{u}Worse", v["subj_worse"]); mac(f"Av{t}{u}Tied", v["subj_tied"])
        mac(f"Av{t}{u}P", ptxt(v["p_sign_subject"])); mac(f"Av{t}{u}Diff", f"{100*v['diff']:.0f}")
        mac(f"Av{t}{u}DiffCI", f"{100*v['diff_ci'][0]:.0f}--{100*v['diff_ci'][1]:.0f}")
if DT:
    d = DT["0.02"]; mac("AvLat", f"{d['lat_median']:.0f}"); mac("AvLatIQR", f"{d['lat_iqr'][0]:.0f}--{d['lat_iqr'][1]:.0f}")
    mac("AvSleepDet", d["sleep_det"]); mac("AvSleepN", d["sleep_n"]); mac("AvZeroFA", d["zero_fa_subjects"]); mac("AvSubjAll", d["subjects"])
    mc = d["modal_choices"][0]; mac("AvModalN", mc[1]); mac("AvModalKey", mc[0].replace("(", "").replace(")", ""))
DF = json.load(open(H.parent / "evaluation" / "results" / "audit" / "audit_s2_defaults.json"))
mac("AvDefDet", DF["det"]); mac("AvDefN", DF["n"]); mac("AvDefFAday", f"{DF['fa_per_day']:.2f}"); mac("AvDefSens", pc(DF["det"]/DF["n"]))
rr = list(RT.values())
mac("RcFiles", len(rr))
mac("RcBlinkLo", f"{min(r['blink_ratio_recon_over_FP1F7'] for r in rr):.2f}"); mac("RcBlinkHi", f"{max(r['blink_ratio_recon_over_FP1F7'] for r in rr):.2f}")
mac("RcWrongLo", f"{min(r['wrongpol_blink_ratio'] for r in rr):.2f}"); mac("RcWrongHi", f"{max(r['wrongpol_blink_ratio'] for r in rr):.2f}")
mac("RcQuantHi", f"{max(r['quant_noise_rms_uV'] for r in rr):.2f}")
(H / "numbers_audit.tex").write_text("\n".join(out) + "\n"); print(len(out), "macros")
